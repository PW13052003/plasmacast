FORECAST_DAYS = 30


def build_feature_row(date, weather_row, lag_df, us_holidays):
    """
    Builds one feature row for a single (center, date) combination,
    matching the exact 13-feature set the model was trained on.

    Lag features are pulled from lag_df — a rolling buffer of recent
    actual + previously-predicted donor counts for this center.

    Args:
        date (pd.Timestamp): The forecast date.
        weather_row (pd.Series): Row with temp_max and precipitation.
        lag_df (pd.DataFrame): Recent donor history (columns: date, donor_count).
        us_holidays: holidays.US() instance.

    Returns:
        dict or None: Feature dict ready for model.predict(), or None if not
                      enough lag history yet.
    """
    dow   = date.dayofweek
    month = date.month
    season_map = {12: 0, 1: 0, 2: 0, 3: 1, 4: 1, 5: 1,
                  6: 2, 7: 2, 8: 2, 9: 3, 10: 3, 11: 3}

    lag7_date  = date - timedelta(days=7)
    lag14_date = date - timedelta(days=14)

    lag7_rows  = lag_df[lag_df["date"] == lag7_date]
    lag14_rows = lag_df[lag_df["date"] == lag14_date]

    if lag7_rows.empty or lag14_rows.empty:
        return None

    lag7  = float(lag7_rows["donor_count"].values[0])
    lag14 = float(lag14_rows["donor_count"].values[0])

    recent_7  = lag_df[lag_df["date"] < date].tail(7)["donor_count"]
    recent_14 = lag_df[lag_df["date"] < date].tail(14)["donor_count"]

    if len(recent_7) < 7 or len(recent_14) < 14:
        return None

    return {
        "temp_max":          float(weather_row["temp_max"]),
        "precipitation":     float(weather_row["precipitation"]),
        "day_of_week":       dow,
        "is_holiday":        int(date.date() in us_holidays),
        "month":             month,
        "year":              date.year,
        "day_of_year":       date.dayofyear,
        "is_weekend":        int(dow >= 5),
        "season":            season_map[month],
        "donor_lag_7":       lag7,
        "donor_lag_14":      lag14,
        "rolling_7day_avg":  float(recent_7.mean()),
        "rolling_14day_avg": float(recent_14.mean()),
    }


def get_seed_history(center_id):
    """
    Loads the last 30 days of actual donor counts from donor_data_featured.csv
    to seed the lag and rolling features for the first 14 forecast days.

    The training data ends 2023-12-31. We use the last 30 rows of that data
    as our "recent history", then remap the dates to be the 30 days immediately
    before today so the lag lookups (date - 7 days, date - 14 days) line up
    with the forecast window.

    Args:
        center_id (str): e.g. "center_philly"

    Returns:
        pd.DataFrame: Columns: date, donor_count — 30 rows ending yesterday.
    """
    csv_path = os.path.join(DATA_DIR, "donor_data_featured.csv")
    df = pd.read_csv(csv_path)
    df["date"] = pd.to_datetime(df["date"])

    center_df = (
        df[df["center_id"] == center_id]
        .sort_values("date")
        .tail(30)
        [["donor_count"]]
        .reset_index(drop=True)
    )

    # Remap dates: last row = yesterday, so lag_7 / lag_14 line up with today onward
    today = pd.Timestamp(datetime.today().date())
    new_dates = [today - timedelta(days=(29 - i)) for i in range(30)]
    center_df["date"] = new_dates

    return center_df[["date", "donor_count"]]


def main():
    print("=== PlasmaCast Static Export ===\n")

    model_path = os.path.join(DATA_DIR, "model.pkl")
    if not os.path.exists(model_path):
        raise FileNotFoundError(
            f"Model not found at {model_path}. Run: python3 src/model.py first."
        )

    bundle   = joblib.load(model_path)
    model    = bundle["model"]
    features = bundle["features"]
    print(f"Model loaded. Features: {features}\n")

    us_holidays = holidays.US()
    today = pd.Timestamp(datetime.today().date())

    # Build a simple weather lookup: use seasonal defaults keyed by month.
    # Open-Meteo's forecast API caps at 16 days, and we need 30 days.
    # Rather than stitching two APIs, we use the last known same-season
    # values from the training data for all 30 days (good enough for a
    # static demo — the model is much more sensitive to lag/day-of-week
    # than to exact temperature).
    SEASONAL_WEATHER = {
        1:  {"temp_max": 2.0,  "precipitation": 2.5},
        2:  {"temp_max": 4.0,  "precipitation": 2.5},
        3:  {"temp_max": 11.0, "precipitation": 3.0},
        4:  {"temp_max": 17.0, "precipitation": 3.0},
        5:  {"temp_max": 23.0, "precipitation": 3.5},
        6:  {"temp_max": 28.0, "precipitation": 3.0},
        7:  {"temp_max": 31.0, "precipitation": 3.5},
        8:  {"temp_max": 30.0, "precipitation": 3.5},
        9:  {"temp_max": 25.0, "precipitation": 3.0},
        10: {"temp_max": 18.0, "precipitation": 3.0},
        11: {"temp_max": 10.0, "precipitation": 3.0},
        12: {"temp_max": 4.0,  "precipitation": 2.5},
    }

    output = {}

    for center_id, info in CENTERS.items():
        city = info["city"]
        print(f"Forecasting {city}...")

        lag_df = get_seed_history(center_id)
        predictions = []

        for day_offset in range(FORECAST_DAYS):
            date = today + timedelta(days=day_offset)
            weather = SEASONAL_WEATHER[date.month]
            weather_row = pd.Series(weather)

            row = build_feature_row(date, weather_row, lag_df, us_holidays)
            if row is None:
                print(f"  Still not enough lag for {date.date()}, skipping.")
                continue

            X    = pd.DataFrame([row])[features]
            pred = float(model.predict(X)[0])
            pred_int = max(0, int(round(pred)))

            predictions.append({
                "date": date.strftime("%Y-%m-%d"),
                "predicted_donors": pred_int,
            })

            # Append prediction into lag_df so future days can use it as lag input
            new_row = pd.DataFrame([{"date": date, "donor_count": pred_int}])
            lag_df  = pd.concat([lag_df, new_row], ignore_index=True)

        output[center_id] = predictions
        if predictions:
            print(f"  {len(predictions)} days. Example: {predictions[0]}")
        else:
            print(f"  WARNING: 0 predictions generated for {city}!")

    os.makedirs(DOCS_DIR, exist_ok=True)
    out_path = os.path.join(DOCS_DIR, "predictions.json")
    with open(out_path, "w") as f:
        json.dump(output, f, indent=2)

    print(f"\nExported {len(output)} centers → {out_path}")
    print("Done! Commit docs/predictions.json to update the GitHub Pages site.")


if __name__ == "__main__":
    main()